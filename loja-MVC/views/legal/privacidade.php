        <p>
            Exclusivamente para processar e entregar o seu pedido: identificar o
            comprador, calcular o frete/entrega, emitir a cobrança e confirmar o
            pagamento. A base legal é a <strong>execução de contrato</strong>
            (art. 7º, V, da LGPD) — ou seja, esses dados são necessários para
            concluir a compra que você está fazendo.
        </p>

        <h2>3. Com quem compartilhamos</h2>
        <p>
            Compartilhamos os dados necessários ao pagamento (nome, e-mail, CPF,
            telefone e endereço) com o <strong>PagBank (PagSeguro)</strong>,
            processador de pagamentos responsável por cobrar cartão, Pix ou
            boleto. Não vendemos nem compartilhamos seus dados com terceiros
            para fins de marketing.
        </p>

        <h2>4. Cookies</h2>
        <p>
            Usamos apenas um cookie de sessão, estritamente necessário para o
            funcionamento do carrinho de compras e do checkout (ele não existe
            para rastreamento ou publicidade). Esse cookie é apagado quando você
            fecha o navegador ou finaliza/abandona a compra.
        </p>

        <h2>5. Por quanto tempo guardamos seus dados</h2>
        <p>
            Guardamos os dados do pedido pelo prazo necessário para cumprir
            obrigações legais, fiscais e para eventual atendimento pós-venda
            (trocas, garantia, suporte).
        </p>

        <h2>6. Seus direitos</h2>
